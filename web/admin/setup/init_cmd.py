import os
import tempfile

import core.mw as mw

def cmdContent():
    script = mw.getPanelDir() + '/scripts/init.d/pm.tpl'
    content = mw.readFile(script)
    content = content.replace("{$SERVER_PATH}", mw.getPanelDir())
    content += "\n# Generated by pmpanel\n"
    return content


def write_command(path, content):
    if os.path.exists(path):
        previous = mw.readFile(path)
        if previous == content:
            return
        if path.startswith('/etc/') and '# make:' not in previous and '# Generated by pmpanel' not in previous:
            return
    with tempfile.NamedTemporaryFile(mode='w', dir=os.path.dirname(path), delete=False) as output:
        try:
            output.write(content)
            output.flush()
            os.fchmod(output.fileno(), 0o755)
            os.replace(output.name, path)
        finally:
            if os.path.exists(output.name):
                os.unlink(output.name)


def init_cmd():
    cmd_content = cmdContent()
    script_bin = mw.getPanelDir() + '/scripts/init.d/pm'
    write_command(script_bin, cmd_content)

    # 在linux系统中,确保/etc/init.d存在
    if not mw.isAppleSystem() and not os.path.exists("/etc/rc.d/init.d"):
        mw.execShell('mkdir -p /etc/rc.d/init.d')

    if not mw.isAppleSystem() and not os.path.exists("/etc/init.d"):
        mw.execShell('mkdir -p /etc/init.d')
    # initd
    if os.path.exists('/etc/rc.d/init.d'):
        initd_bin = '/etc/rc.d/init.d/pm'
        write_command(initd_bin, cmd_content)
        # 加入自启动
        mw.execShell('command -v chkconfig && chkconfig --add pm')


    if os.path.exists('/etc/init.d'):
        initd_bin = '/etc/init.d/pm'
        write_command(initd_bin, cmd_content)
        # 加入自启动
        mw.execShell('command -v update-rc.d && update-rc.d -f pm defaults')

    # sys_name = mw.getOsName()
    # if sys_name == 'opensuse':
    #     init_cmd_systemd()
    return True


